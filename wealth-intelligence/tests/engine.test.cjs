"use strict";
const assert=require("node:assert/strict");
const path=require("node:path");
global.window=global;
require(path.join(__dirname,"..","engine.js"));
const E=global.WealthEngine;
const demo=E.normalize(E.DEMO);
assert.equal(demo.positions.length,7);
const p=E.portfolio(demo);
assert.ok(Math.abs(p.total-1329973.5)<0.01);
assert.ok(p.total>p.basis);
assert.equal(p.classes.reduce((s,c)=>s+c.value,0),p.total);
assert.ok(E.score(demo,p)>=0 && E.score(demo,p)<=100);
assert.ok(E.insights(demo,p).length>2);
const empty=E.emptyData();
assert.equal(E.portfolio(empty).total,0);
assert.equal(E.score(empty,E.portfolio(empty)),0);
const h=E.historyAnalysis([{date:"2026-01-01",total:100,flow:0},{date:"2026-02-01",total:120,flow:10}]);
assert.ok(Math.abs(h.twr-10)<1e-9);
const z=E.forecast(1000,{target:2200,monthly:100,years:1,rate:0,vol:0,inflation:0});
assert.ok(Math.abs(z.median-2200)<1e-5);
assert.equal(z.probability,100);
const stochastic=E.forecast(p.total,demo.assumptions);
assert.equal(stochastic.series.length,16);
assert.ok(stochastic.series.every(x=>x.p10<=x.p50&&x.p50<=x.p90));
assert.equal(stochastic.median,E.forecast(p.total,demo.assumptions).median,"fixed random seed should make it repeatable");
assert.throws(()=>E.normalize({version:1,positions:[],history:[{date:"2026-01-01",total:-10}]}));
console.log("Wealth Intelligence engine: all assertions passed.");
